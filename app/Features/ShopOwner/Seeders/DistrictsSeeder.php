            $country = DB::table('countries')
                ->where('name', $countryName)
                ->first();

            if (! $country) {
                throw new RuntimeException(
                    "Country '{$countryName}' not found in countries table."
                );
            }

            foreach ($countryCities as $cityName => $cityDistricts) {

                $city = DB::table('cities')
                    ->where('country_id', $country->id)
                    ->where('name', $cityName)
                    ->first();

                if (! $city) {
                    throw new RuntimeException(
                        "City '{$cityName}' not found for country '{$countryName}'."
                    );
                }

                $rows = collect($cityDistricts)
                    ->unique()
                    ->map(fn($districtName) => [
                        'name' => $districtName,
                        'city_id' => $city->id,
                    ])
                    ->values()
                    ->all();

                DB::table('districts')->upsert(
                    $rows,
                    ['city_id', 'name'],
                    []
                );
            }
